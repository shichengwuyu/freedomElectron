export const LEGAL_AGREEMENT_STORAGE_KEY = 'yanzhi-ai.legal-agreement';
export const LEGAL_AGREEMENT_VERSION = '2026-08-10';

export function isLegalAgreementAccepted(value) {
  return value?.accepted === true;
}

export function hasAcceptedLegalAgreement(storage) {
  try {
    const raw = storage?.getItem?.(LEGAL_AGREEMENT_STORAGE_KEY);
    if (!raw) return false;
    return isLegalAgreementAccepted(JSON.parse(raw));
  } catch {
    return false;
  }
}

export function saveLegalAgreementAcceptance(storage, version = LEGAL_AGREEMENT_VERSION, now = Date.now()) {
  try {
    if (!storage || typeof storage.setItem !== 'function') return false;
    storage?.setItem?.(LEGAL_AGREEMENT_STORAGE_KEY, JSON.stringify({
      accepted: true,
      version,
      acceptedAt: new Date(now).toISOString(),
    }));
    return true;
  } catch {
    return false;
  }
}

