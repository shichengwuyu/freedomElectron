function removeThreeViewConflicts(value = '') {
  return String(value || '')
    .replace(/严禁三视图、侧面人物、背面人物、多角度角色表、多个重复全身人物；?/g, '')
    .replace(/严禁三视图、侧面人物、背面人物、多角度角色表、多个重复全身人物/g, '')
    .replace(/三视图、侧面人物、背面人物、多角度角色表、多个重复全身人物、?/g, '')
    .replace(/不要侧面、背面、三视图或多角度小人。?/g, '')
    .replace(/只要正面全身，?/g, '')
    .replace(/；{2,}/g, '；')
    .replace(/，{2,}/g, '，')
    .replace(/。，/g, '，')
    .trim();
}

function extractCharacterStyleDirection(prompt = '') {
  const value = String(prompt || '');
  const match = value.match(/整体风格：\n([\s\S]*?)(?=\n\n[^\n：]+：|$)/);
  return match?.[1]?.trim() || '严格沿用用户当前选择的画风提示词。';
}

