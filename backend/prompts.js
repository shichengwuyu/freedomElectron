const CREATURE_SWARM_RE = /(?:虫群|兽群|群体生物|群居|集群|蜂群|蚁群|蝗群|鱼群|鸟群|成群)/;
const CREATURE_MECHANICAL_RE = /(?:机械兽|傀儡兽|机关兽|机甲|机械骨架|装甲|能源核心|金属关节|仿生机械)/;
const CREATURE_HORROR_RE = /(?:诡兽|尸傀|异变体|畸变|腐朽|腐烂|亡灵|血肉怪物|异常结构|诡异|邪祟)/;
const CREATURE_GIANT_RE = /(?:巨兽|深海巨兽|山岳般|城池般|体长约?(?:十|百|千)丈|肩高约?(?:三|四|五|六|七|八|九|十)人)/;
const CREATURE_COMPANION_RE = /(?:宠物型|伴生灵兽|契约灵宠|灵宠|幼兽|亲和|活泼可爱|小巧灵动)/;
const CREATURE_DIVINE_RE = /(?:神兽|仙兽|灵兽|圣兽|瑞兽|祥瑞|神圣|仙气|高贵优雅|尊贵|空灵)/;
const CREATURE_FIERCE_RE = /(?:凶兽|魔兽|猛兽|凶戾|暴虐|狰狞|攻击性|压迫感|猎食者)/;

function creaturePresentationKind(creature = {}) {
  const text = [
    creature.archetype,
    creature.species,
    creature.size,
    creature.headFeatures,
    creature.anatomy,
    creature.pose,
    creature.surface,
    creature.featureMarks,
    creature.ornamentArmor,
    creature.aura,
  ].filter(Boolean).join(' ');
  if (CREATURE_SWARM_RE.test(text)) return 'swarm';
  if (CREATURE_MECHANICAL_RE.test(text)) return 'mechanical';
  if (CREATURE_HORROR_RE.test(text)) return 'horror';
  if (CREATURE_GIANT_RE.test(text)) return 'giant';
  if (CREATURE_COMPANION_RE.test(text)) return 'companion';
  if (CREATURE_DIVINE_RE.test(text)) return 'divine';
  if (CREATURE_FIERCE_RE.test(text)) return 'fierce';
  return 'generic';
}

function creatureCompositionGuide(creature = {}) {
  const common = '妖兽角色资产设定图，构图适配当前输出画幅，不固定横版或正方形；背景保持简洁，主体轮廓完整清楚。';
  switch (creaturePresentationKind(creature)) {
    case 'swarm':
      return `${common}以完整群体为主体，清楚呈现集群外轮廓、数量密度、队列层次和代表性个体差异；所有个体属于同一物种体系，不添加局部特写小窗、文字标签或人类角色。`;
    case 'mechanical':
      return `${common}只呈现一只完整机械兽，以三分之四侧前方全身展示机械骨架、装甲分层、关节连接、能源核心、尾翼或机械爪结构；采用稳定资产展示姿态，不添加局部特写小窗或人类比例剪影。`;
    case 'horror':
      return `${common}只呈现一只完整诡兽，以侧前方全身展示稳定的异常轮廓、非对称结构、肢体连接和体表材质；姿态克制但令人不安，不表现正在攻击或剧情打斗，不添加局部特写小窗或人类角色。`;
    case 'giant':
      return `${common}只呈现一只完整巨兽，从头到尾或翼尖到足部完整入镜，使用低机位或侧前方全身角度突出巨大体量、重量与结构比例；可加入无文字的简洁比例刻度或地面网格，不使用人形剪影，不添加局部特写小窗。`;
    case 'companion':
      return `${common}只呈现一只完整宠物型灵兽，采用自然、灵动、亲和的三分之四侧身全身姿态，清楚展示面部、耳角、四肢、翼尾与装饰；保持精致生物比例，不自动画成低幼 Q 版，不添加局部特写小窗或重复主体。`;
    case 'divine':
      return `${common}只呈现一只完整神兽或灵兽，采用高贵优雅的三分之四侧身全身展示，姿态舒展；四足生物可轻抬一只前足，飞行生物则自然展开翼部，完整呈现头部、角冠、躯干、四肢、翼尾、饰甲和稳定伴生灵气，不添加局部特写小窗或人类比例剪影。`;
    case 'fierce':
      return `${common}只呈现一只完整凶兽，以侧前方全身展示头部、躯干、攻击器官、四肢、翼尾和爪牙比例；根据物种采用自然站立或低位蓄势姿态，突出力量和压迫感，但不表现攻击过程、战斗对象或剧情场景，不添加局部特写小窗。`;
    default:
      return `${common}只呈现一只完整生物，采用自然三分之四侧前方全身展示，从头到尾完整入镜，清楚呈现头部、躯干、四肢、翼尾的结构比例、体表材质与标志性细节；不添加局部特写小窗、人类比例剪影或重复主体。`;
  }
}

