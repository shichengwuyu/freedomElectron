const KNOWN_ASSET_LIST_LIMIT = 120;

// 把「已有资产清单」渲染成紧凑文本：每类一行，人物额外带上别名
// known 形如 { character: [{ name, aliases }], scene: ['青云城', ...], ... }
function formatKnownAssetRoster(known, categories) {
  if (!known || typeof known !== 'object') return '';
  const lines = [];
  for (const [category, label] of Object.entries(EXTRACTION_CATEGORY_LABELS)) {
    if (Array.isArray(categories) && categories.length && !categories.includes(category)) continue;
    const entries = Array.isArray(known[category]) ? known[category] : [];
    const items = [];
    for (const entry of entries) {
      const name = String((typeof entry === 'string' ? entry : entry?.name) || '').trim();
      if (!name) continue;
      const rawAliases = typeof entry === 'string' ? '' : entry?.aliases;
      const aliases = (Array.isArray(rawAliases) ? rawAliases.join('、') : String(rawAliases || '')).trim();
      items.push(aliases ? `${name}（又称：${aliases}）` : name);
      if (items.length >= KNOWN_ASSET_LIST_LIMIT) break;
    }
    if (items.length) lines.push(`【已有${label}】${items.join('，')}`);
  }
  return lines.join('\n');
}

