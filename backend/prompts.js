function promptDetailLines(items = []) {
  return items
    .filter(([, value]) => String(value || '').trim())
    .map(([label, value]) => `${label}：${String(value).trim()}`);
}

function elementPromptDetails(category, source = {}) {
  if (category === 'character') {
    return promptDetailLines([
      ['人物名称', source.name],
      ['人物气质与人设定位', source.identity],
      ['外貌', source.appearance],
      ['身高比例与体态', source.body],
      ['发型发色', source.hair],
      ['服装造型', source.clothing],
      ['妆容配饰', source.makeupAccessories],
      ['其他特征', source.traits || source.description],
    ]);
  }
  if (category === 'group') {
    const members = (Array.isArray(source.members) ? source.members : []).map((member, index) => {
      const label = member?.label || member?.knownName || `成员${index + 1}`;
      const details = [member?.appearance, member?.hair, member?.body, member?.clothing, member?.distinction]
        .filter(Boolean)
        .join('；');
      return details ? `${label}：${details}` : label;
    }).join('\n');
    return promptDetailLines([
      ['群像名称', source.name],
      ['共同身份', source.identity],
      ['人数', source.memberCount],
      ['共同服装', source.sharedClothing],
      ['成员设定', members],
      ['构图信息', source.composition],
      ['补充描述', source.description],
    ]);
  }
  if (category === 'scene') {
    return promptDetailLines([
      ['场景名称', source.name],
      ['环境类型', source.envType],
      ['时间', source.time],
      ['氛围', source.atmosphere],
      ['主要特征', source.features],
      ['光线与天气', source.light],
      ['色彩', source.color],
      ['补充描述', source.description],
    ]);
  }
  if (category === 'prop') {
    return promptDetailLines([
      ['道具名称', source.name],
      ['外观形状', source.shape],
      ['材质', source.material],
      ['颜色', source.color],
      ['尺寸', source.size],
      ['纹饰与标记', source.marks],
      ['补充描述', source.description],
    ]);
  }
  if (category === 'effect') {
    return promptDetailLines([
      ['特效名称', source.name],
      ['特效类型', source.effectType],
      ['触发来源', source.source],
      ['核心视觉形态', source.visualCore],
      ['运动轨迹', source.motion],
      ['颜色与发光', source.colorLight],
      ['规模与距离', source.scale],
      ['环境互动', source.environmentInteraction],
      ['特写焦点', source.closeup],
      ['补充描述', source.description],
    ]);
  }
  return promptDetailLines([
    ['生物名称', source.name],
    ['定位与气质', source.archetype],
    ['物种类型', source.species],
    ['体型规模', source.size],
    ['头部与面部', source.headFeatures],
    ['身体结构', source.anatomy],
    ['稳定姿态', source.pose],
    ['体表材质与配色', source.surface],
    ['标志器官与记忆点', source.featureMarks],
    ['饰甲与装置', source.ornamentArmor],
    ['稳定伴生效果', source.aura],
    ['常出没环境', source.habitat],
    ['补充描述', source.description],
  ]);
}

