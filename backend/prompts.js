function appendExtractionCategoryScope(prompt, categories) {
  const total = Object.keys(EXTRACTION_CATEGORY_LABELS).length;
  if (!Array.isArray(categories) || !categories.length || categories.length >= total) return prompt;
  const labels = categories.map((category) => EXTRACTION_CATEGORY_LABELS[category]).filter(Boolean);
  if (!labels.length) return prompt;
  return `${prompt}\n\n本次只提取以下类别：${labels.join('、')}。其他类别对应数组必须输出空数组 []，不要顺带分析或新增其他类别。`;
}

export function buildExtractionSystemPrompt(promptTemplateConfig = null, categories = null, style = 'realistic') {
  const tpl = getPromptTemplate(promptTemplateConfig);
  if (tpl.id === 'second') {
    return appendExtractionCategoryScope(applySecondSetCharacterExtractionPolicy(EXTRACTION_SYSTEM_PROMPT, style), categories);
  }
  const rules = String(tpl.extractionAestheticRules || '').trim();
  let prompt = EXTRACTION_SYSTEM_PROMPT;
  if (!rules) return appendExtractionCategoryScope(prompt, categories);
  const replaced = prompt.replace(XIANXIA_EXTRACTION_AESTHETIC_RULES, rules);
  if (replaced !== prompt) return appendExtractionCategoryScope(replaced, categories);
  if (prompt.includes(rules)) return appendExtractionCategoryScope(prompt, categories);
  prompt = prompt.replace(
    '   人物内容只服务角色库出图',
    `   题材审美补充：${rules}\n   人物内容只服务角色库出图`
  );
  return appendExtractionCategoryScope(prompt, categories);
}

function emptyCharacterParts() {
  return Object.fromEntries(CHARACTER_PROMPT_PART_FIELDS.map((field) => [field, '']));
}

export function emptyCharacterPartsEdited() {
  return Object.fromEntries(CHARACTER_PROMPT_PART_FIELDS.map((field) => [field, false]));
}

export function normalizeCharacterPromptParts(parts = {}) {
  const normalized = emptyCharacterParts();
  for (const field of CHARACTER_PROMPT_PART_FIELDS) {
    normalized[field] = String(parts?.[field] || '').trim();
  }
  normalized.negative = cleanCharacterNegativeText(normalized.negative);
  return normalized;
}

export function normalizeCharacterPartsEdited(partsEdited = {}) {
  const normalized = emptyCharacterPartsEdited();
  for (const field of CHARACTER_PROMPT_PART_FIELDS) {
    normalized[field] = !!partsEdited?.[field];
  }
  return normalized;
}

