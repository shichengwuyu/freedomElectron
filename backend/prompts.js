function replaceCharacterStructureSection(prompt, composition) {
  const value = String(prompt || '').trim();
  const replaced = value.replace(/图片结构：\n[\s\S]*?(?=\n\n背景与光线：|\n\n绝对注意事项：|$)/, `图片结构：\n${composition}`);
  return replaced === value ? `${value}\n\n图片结构：\n${composition}` : replaced;
}

function appendCharacterNegativeRule(prompt, rule) {
  const value = String(prompt || '');
  const replaced = value.replace(/绝对注意事项：\n[\s\S]*$/, (section) => `${section}\n${rule}`);
  return replaced === value ? `${value}\n\n绝对注意事项：\n${rule}` : replaced;
}

export function applyCharacterImageMode(prompt, mode = 'double') {
  const normalizedMode = normalizeCharacterImageMode(mode);
  if (normalizedMode === 'double') return prompt;
  const cleaned = removeThreeViewConflicts(prompt);
  if (normalizedMode === 'threeView') {
    const withStructure = replaceCharacterStructureSection(cleaned, CHARACTER_THREE_VIEW_COMPOSITION);
    return appendCharacterNegativeRule(withStructure, THREE_VIEW_NEGATIVE_RULE);
  }
  if (normalizedMode === 'threeViewSplitFace') {
    const withStructure = replaceCharacterStructureSection(cleaned, CHARACTER_SPLIT_FACE_THREE_VIEW_COMPOSITION);
    return appendCharacterNegativeRule(withStructure, SPLIT_FACE_NEGATIVE_RULE);
  }
  if (normalizedMode === 'threeViewPainting') {
    const withStructure = replaceCharacterStructureSection(cleaned, CHARACTER_PAINTING_THREE_VIEW_COMPOSITION);
    return appendCharacterNegativeRule(withStructure, PAINTING_NEGATIVE_RULE);
  }
  const withStructure = replaceCharacterStructureSection(cleaned, characterProfessionalDesignComposition(cleaned));
  return appendCharacterNegativeRule(withStructure, PROFESSIONAL_DESIGN_NEGATIVE_RULE);
}

